# you want to simulate tea heating . it starts at 40c and boils at 100c

# task :
#    use a while loop 
#    increase temp by 15 until it reaches or exceeds 100 
#    print each temp step 

temperature = 40

while temperature < 100 :
    print(f"current temperature: {temperature}")
    temperature += 15 

print("tea is ready to boil")    